import { readFileSync } from "node:fs";
import { dirname } from "node:path";
import { getSystemMessageText } from "@earendil-works/pi-ai";
import { expect, test } from "vitest";
import { getReadmePath } from "../src/config.ts";
import { createSyntheticSourceInfo } from "../src/core/source-info.ts";
import {
	type BuildSystemPromptOptions,
	buildSystemPrompt,
	buildSystemPromptDocument,
	buildSystemPromptSections,
} from "../src/core/system-prompt.ts";
import {
	renderSystemPromptDocument,
	systemPromptBuilderForOutput,
	systemPromptOutputMatches,
} from "../src/core/system-prompt-document.ts";

// Frozen from yesterday's session, entry 6f0173f7. Expected output is not generated by production code.
const fixture = JSON.parse(readFileSync(new URL("./fixtures/system-prompt-2026-11-02.json", import.meta.url), "utf8"));
const input: BuildSystemPromptOptions = {
	...fixture.input,
	skills: fixture.input.skills.map((skill: { filePath: string }) => ({
		...skill,
		sourceInfo: createSyntheticSourceInfo(skill.filePath, { source: "test" }),
	})),
};
// Only the installation directory varies between machines; keep all other bytes unchanged.
const normalize = (text: string) => text.replaceAll(dirname(getReadmePath()), "<CODING_AGENT>");
const historicalOutput = {
	content: fixture.expected.content as string,
	sections: Object.fromEntries(
		Object.entries(fixture.expected.sections as Record<string, string>).map(([name, text]) => [
			name,
			text.replaceAll("<CODING_AGENT>", dirname(getReadmePath())),
		]),
	),
};

test("an unused override does not cause a mismatch against the recorded sections", () => {
	const builder = {
		document: buildSystemPromptDocument({ ...input, forceSystemPrompt: "Unused extension override" }),
		excludedIds: [],
	};
	const effective = systemPromptBuilderForOutput(builder, historicalOutput);
	expect(effective.document.forced).toBeUndefined();
	expect(builder.document.forced?.text).toBe("Unused extension override");
	expect(systemPromptOutputMatches(builder, historicalOutput)).toBe(true);
	expect(systemPromptOutputMatches({ ...effective, excludedIds: ["preamble"] }, historicalOutput)).toBe(false);
});

test("an effective full-text override is preserved and compared as text", () => {
	const text = fixture.expected.text.replaceAll("<CODING_AGENT>", dirname(getReadmePath()));
	const builder = { document: buildSystemPromptDocument({ ...input, forceSystemPrompt: text }), excludedIds: [] };
	const output = { content: text };
	expect(systemPromptBuilderForOutput(builder, output)).toBe(builder);
	expect(systemPromptOutputMatches(builder, output)).toBe(true);
	expect(systemPromptOutputMatches(builder, { content: `${text}\nchanged` })).toBe(false);
});

test("prompt generation exactly matches the recorded 2026-11-02 chat prompt", () => {
	expect(normalize(buildSystemPrompt(input))).toBe(fixture.expected.text);
	expect(
		Object.fromEntries(
			Object.entries(buildSystemPromptSections(input)).map(([name, text]) => [name, normalize(text)]),
		),
	).toEqual(fixture.expected.sections);
});

test("the Builder exactly reproduces that same historical prompt without edits", () => {
	const document = buildSystemPromptDocument(input);
	const rendered = renderSystemPromptDocument(document, []);
	const text = getSystemMessageText({ role: "system", ...rendered, timestamp: 0 });
	expect(normalize(text)).toBe(fixture.expected.text);
	expect(rendered.content).toBe(fixture.expected.content);
	expect(
		Object.fromEntries(Object.entries(rendered.sections ?? {}).map(([name, text]) => [name, normalize(text)])),
	).toEqual(fixture.expected.sections);
});
